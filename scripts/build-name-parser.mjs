// The injected scripts and TypeScript consumers run the same parser source.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { build } from "vite";
for (const [source, output, name] of [
  ["src/util/personName.ts", "person-name.js", "BettersPersonNames"],
  ["src/portal/mappingTargets.ts", "mapping-targets.js", "BettersMappingTargets"]
]) {
  const bundle = await build({ configFile:false, logLevel:"silent", build:{ write:false, minify:false,
    lib:{ entry:fileURLToPath(new URL("../" + source, import.meta.url)), name, formats:["iife"] }
  } });
  const js = (Array.isArray(bundle) ? bundle[0] : bundle).output.find(item => item.type === "chunk").code;
  writeFileSync(new URL("../public/portal/" + output, import.meta.url),
    `// Generated by scripts/build-name-parser.mjs; edit ${source}.\n` + js + `\nglobalThis.${name}=${name}; if(typeof module==="object" && module.exports) module.exports=${name};\n`);
}
